#!/usr/bin/env python3
"""test_spawn_tree_binding.py — a record certifies only the tree whose shas it carries.

WHY THIS EXISTS (D5 + D6). `SPAWN-RECORD-BIND` closed D2/D3/D4 and deliberately left two
defects open, because both need `cell.py`, which `TRANCH1-DRYRUN` had pinned:

  D5  the record was NOT tree-bound. Reproduction, exactly as measured: same argv, one
      gate made permissive in a /tmp copy of the tree, the invocation moves exit 4 -> 12,
      and the HISTORICAL exit-4 record still validates OK. A record could therefore be
      presented as a certificate for a run it never described.
  D6  `cell.py`'s refusal writer published a FIXED key list, so the on-disk
      `*.refusal.json` dropped the `instrumentation` block that `SpawnRecord.as_dict()`
      emits -- the document failed the D4 check while the in-process verdict passed.

The fix: `cell.py` writes `cell_sha256`, `spawn_record_sha256`, `argv` and `tree_sha`
into the refusal record (through the recorder's ONE dict shape, which also carries
`instrumentation`), and `validate_refusal` REQUIRES those keys and compares the two shas
against the files named by `--cell-path` / `--spawn-record-path`.

Each test is a red for one half of that sentence. Every run is offline: the gate suite's
stub runner records that it was invoked and sends nothing.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
LONGRUN = os.path.dirname(HERE)
PY = sys.executable

sys.path.insert(0, HERE)
import test_spawn_classification as sc  # noqa: E402  (the offline refusal harness)

spawn_record = sc.spawn_record
CELL = sc.CELL
VALIDATOR = os.path.join(LONGRUN, "spawn_record.py")

D5_SENTENCE = ("no tree binding (D5): record names neither cell_sha256 nor "
               "spawn_record_sha256")


def _cli(doc, tmp, *extra, name="record.json"):
    """Validate one document through the real CLI; its exit status is the verdict."""
    path = os.path.join(tmp, name)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(doc, fh)
    cmd = [PY, VALIDATOR, "--validate", path,
           "--exit-code", str(doc.get("exit"))] + list(extra)
    return subprocess.run(cmd, capture_output=True, text=True)


def _permissive_g1_tree(tmp):
    """The D5 tree: a /tmp cell whose G1 ALLOWS instead of refusing.

    This is "one gate made permissive in a /tmp copy of the tree". It is not the same
    file as the honest `cell.py`, so it carries a different sha -- which is the whole
    point: the historical record describes the honest tree, and this tree is not it.
    """
    path = os.path.join(tmp, "perm-g1", "cell.py")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# D5 ATTACK TREE: the ledger gate (G1) is permissive here.\n"
                 "import sys\n"
                 "sys.path.insert(0, %r)\n"
                 "import cell as _honest\n"
                 "def _allow(args):\n"
                 "    # the SAME verdict shape an allow takes, minus the refusal\n"
                 "    return {'gate': 'G1', 'what': 'ledger-cap', 'ok': True,\n"
                 "            'short': 'G1 53/1000 requests', 'cap': 1000, 'reserve': 0,\n"
                 "            'spent': 0, 'counting_tool': 'request_ledger.py'}\n"
                 "_honest.eval_gate_ledger = _allow\n"
                 "sys.exit(_honest.main(sys.argv[1:]))\n" % (LONGRUN,))
    return path


class TreeBinding(unittest.TestCase):
    """D5: the record names its tree, and the validator holds it to that name."""

    def test_d5_matching_tree_is_accepted(self):
        # The honest direction: a record generated by THIS cell.py against THIS tree is
        # accepted with no repair step, and it names the files it was generated from.
        tmp = tempfile.mkdtemp(prefix="d5-match-")
        try:
            case = sc.run_case(tmp, 4)
            doc = case["doc"]
            self.assertEqual(case["exit"], 4, case["log"][-2000:])
            self.assertEqual(doc.get("cell_sha256"), spawn_record.sha256_file(CELL),
                             "the record does not name the cell.py that wrote it")
            self.assertEqual(doc.get("spawn_record_sha256"),
                             spawn_record.sha256_file(VALIDATOR))
            self.assertTrue(doc.get("argv"), "the record names no process argv")
            self.assertRegex(doc.get("tree_sha") or "", r"^(unstamped|[0-9a-f]{40})$")
            proc = _cli(doc, tmp)
            self.assertEqual(proc.returncode, 0,
                             "a record from this very cell.py was refused: %s"
                             % proc.stderr)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_d5_record_without_binding_keys_is_refused(self):
        # Stripping the binding is the bypass a lazy fix invites: the record must be
        # refused by NAME, not quietly accepted because the fields are optional.
        tmp = tempfile.mkdtemp(prefix="d5-strip-")
        try:
            doc = json.loads(json.dumps(sc.run_case(tmp, 4)["doc"]))
            for key in ("cell_sha256", "spawn_record_sha256", "argv", "tree_sha"):
                doc.pop(key, None)
            proc = _cli(doc, tmp, name="stripped.json")
            self.assertEqual(proc.returncode, 1,
                             "a record naming no tree validated OK: %s" % proc.stdout)
            self.assertIn(D5_SENTENCE, proc.stderr)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_d5_historical_record_against_permissive_tree_is_refused(self):
        # THE ATTACK, reproduced: the historical exit-4 record is presented while the
        # tree whose G1 is permissive is what the invocation actually runs. Measured
        # 4 -> 12 for the same argv. Before D5 the historical record validated OK.
        tmp = tempfile.mkdtemp(prefix="d5-attack-")
        try:
            honest = sc.run_case(tmp, 4)
            self.assertEqual(honest["exit"], 4, honest["log"][-2000:])
            historical = honest["doc"]
            perm = _permissive_g1_tree(tmp)
            os.makedirs(os.path.join(tmp, "perm"), exist_ok=True)
            permissive = sc.run_case(os.path.join(tmp, "perm"), 4, cell=perm)
            self.assertNotEqual(permissive["exit"], 4,
                                "the permissive-G1 tree did not change the outcome: the "
                                "attack would be vacuous\n%s"
                                % permissive["log"][-2000:])
            self.assertNotIn("G1 ledger-cap REFUSED", permissive["log"],
                             "G1 still refused: the /tmp tree is not permissive")
            self.assertNotEqual(spawn_record.sha256_file(perm),
                                spawn_record.sha256_file(CELL))
            proc = _cli(historical, tmp, "--cell-path", perm, name="historical.json")
            self.assertEqual(proc.returncode, 1,
                             "the historical record certified a tree it does not "
                             "describe (exit %d): %s"
                             % (proc.returncode, proc.stdout))
            self.assertIn("tree binding mismatch (D5)", proc.stderr)
            self.assertIn("cell_sha256", proc.stderr)
            self.assertIn(spawn_record.sha256_file(perm), proc.stderr,
                          "the refusal does not name the tree it was held against")
            self.assertIn(historical["cell_sha256"], proc.stderr,
                          "the refusal does not name the sha the record carries")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_d5_unstamped_tree_is_labelled_not_invented(self):
        # A tree with no commit (no `.git` anywhere above it) has NO stamp. The record
        # must say `unstamped` -- never an empty field, never a dash, never a plausible
        # invented sha -- and it must reach that answer WITHOUT running `git`, because a
        # recorder that spawned a git child would appear in its own ledger (and in a
        # syscall oracle) as an undeclared spawn. Hence: no `git` on PATH, and no
        # subprocess of any kind.
        tmp = tempfile.mkdtemp(prefix="d5-unstamped-")
        try:
            empty_bin = os.path.join(tmp, "bin")
            os.makedirs(empty_bin)
            bare = os.path.join(tmp, "bare-tree")
            os.makedirs(bare)
            env = {"PATH": empty_bin, "HOME": tmp, "LANG": "C"}
            code = ("import importlib.util, json, sys\n"
                    "spec = importlib.util.spec_from_file_location('sr', %r)\n"
                    "m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)\n"
                    "b = m.tree_binding(argv=['python3', 'cell.py'], repo_dir=%r)\n"
                    "print(json.dumps({k: b[k] for k in "
                    "('tree_sha', 'cell_sha256', 'spawn_record_sha256', 'argv')}))\n"
                    % (VALIDATOR, bare))
            proc = subprocess.run([PY, "-c", code], capture_output=True, text=True,
                                  env=env, timeout=120)
            self.assertEqual(proc.returncode, 0, proc.stderr[-2000:])
            binding = json.loads(proc.stdout.strip().splitlines()[-1])
            self.assertEqual(binding["tree_sha"], spawn_record.TREE_UNSTAMPED,
                             "an unstamped tree was given a stamp: %r"
                             % (binding["tree_sha"],))
            self.assertNotIn(binding["tree_sha"], ("", "-", None))
            # the file shas still bind: an unstamped TREE is not an unbound RECORD
            self.assertRegex(binding["cell_sha256"], r"^[0-9a-f]{64}$")
            self.assertRegex(binding["spawn_record_sha256"], r"^[0-9a-f]{64}$")
            self.assertEqual(binding["argv"], ["python3", "cell.py"])
            # a real tree still yields its commit (the honest twin of the label above)
            self.assertRegex(spawn_record.tree_sha(repo_dir=LONGRUN), r"^[0-9a-f]{40}$")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


class RefusalDocumentShape(unittest.TestCase):
    """D6: the document `cell.py` writes is the document the validator demands."""

    def test_d6_refusal_document_carries_instrumentation(self):
        tmp = tempfile.mkdtemp(prefix="d6-doc-")
        try:
            doc = sc.run_case(tmp, 4)["doc"]  # read straight off disk, no repair helper
            self.assertIn("instrumentation", doc,
                          "the on-disk refusal dropped `instrumentation` (D6): keys %s"
                          % sorted(doc))
            block = doc["instrumentation"]
            for key in spawn_record.INSTRUMENTATION_KEYS:
                self.assertIn(key, block)
            self.assertEqual(block["primitive"], "subprocess.Popen")
            verdict = spawn_record.validate_refusal(doc, doc.get("exit"))
            self.assertTrue(verdict["ok"], verdict["failures"])
            proc = _cli(doc, tmp, name="on-disk.json")
            self.assertEqual(proc.returncode, 0,
                             "the document cell.py wrote does not validate: %s"
                             % proc.stderr)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    unittest.main()
